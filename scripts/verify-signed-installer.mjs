import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createHash, createPublicKey, verify } from 'node:crypto';

const [file, signatureFile, configFile, manifestFile] = process.argv.slice(2);
const config = JSON.parse(readFileSync(configFile, 'utf8'));
const publicLines = Buffer.from(config.plugins.updater.pubkey, 'base64').toString('utf8').trim().split(/\r?\n/);
const publicBytes = Buffer.from(publicLines[1], 'base64');
assert.equal(publicBytes.length, 42);
assert.equal(publicBytes.subarray(0, 2).toString(), 'Ed');
const signatureText = readFileSync(signatureFile, 'utf8').trim();
const lines = Buffer.from(signatureText, 'base64').toString('utf8').trim().split(/\r?\n/);
assert.equal(lines.length, 4);
assert.ok(lines[2].startsWith('trusted comment: '));
const signed = Buffer.from(lines[1], 'base64');
assert.equal(signed.length, 74);
assert.equal(signed.subarray(0, 2).toString(), 'ED', 'Expected prehashed Minisign');
assert.ok(publicBytes.subarray(2, 10).equals(signed.subarray(2, 10)), 'Signing key ID mismatch');
const key = createPublicKey({key: Buffer.concat([Buffer.from('302a300506032b6570032100', 'hex'), publicBytes.subarray(10)]), format: 'der', type: 'spki'});
const content = readFileSync(file);
const verifyContent = (bytes) => verify(null, createHash('blake2b512').update(bytes).digest(), key, signed.subarray(10));
assert.ok(verifyContent(content), 'Installer signature invalid');
assert.ok(verify(null, Buffer.concat([signed.subarray(10), Buffer.from(lines[2].slice(17))]), key, Buffer.from(lines[3], 'base64')), 'Trusted comment signature invalid');
const altered = Buffer.from(content);
altered[altered.length - 1] ^= 1;
assert.equal(verifyContent(altered), false, 'Tampered installer must fail');
const manifest = JSON.parse(readFileSync(manifestFile, 'utf8'));
assert.equal(manifest.version.replace(/^v/, ''), config.version);
assert.equal(manifest.platforms['windows-x86_64'].signature.trim(), signatureText);
console.log(JSON.stringify({version: config.version, signature: 'valid', tamperCheck: 'rejected', sha256: createHash('sha256').update(content).digest('hex'), bytes: content.length}, null, 2));
